#!/usr/bin/env python3
"""Regenerates src/original.js from reference/v5_4_game.js by line ranges.

Run:  python3 -I tools/golden/gen_original.py [path/to/v5_4_game.js]
The blocks are byte-exact copies of the cited lines; only the glue around them is ours.
"""
import hashlib, json, pathlib, sys

REF = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/home/user/spicy-rodents/reference/v5_4_game.js')
OUT = pathlib.Path(__file__).resolve().parent / 'src' / 'original.js'
lines = REF.read_text().split('\n')

def block(a, b):
    return '\n'.join(lines[a - 1:b])

BLOCKS = [
    ("RNG", 80, 89, "mulberry32-style seeded RNG; every random vector set below is drawn with it"),
    ("ROUTE_MOTION", 267, 272, "RouteMotion.advance(t, dir, forward, seconds, speed, length)"),
    ("SMOOTHSTEP", 403, 406, "smoothstep used by baseTerrainHeight (THREE.MathUtils.clamp)"),
    ("BASE_TERRAIN_HEIGHT", 407, 416, "baseTerrainHeight(x, z)"),
    ("RIVER", 419, 435, "RIVER constants"),
    ("RIVER_FUNCTIONS", 436, 457, "riverCenter, inRiverDistrict, insideRiverWater, riverDeckAt"),
    ("TERRAIN_HEIGHT", 458, 464, "terrainHeight(x, z) (uses THREE.MathUtils.smoothstep)"),
    ("HEDGE_PATCHES", 3573, 3579, "hedgePatches table read by the spotted predicate"),
    ("GARDEN", 3590, 3591, "GARDEN_X / GARDEN_Z read by the spotted predicate"),
    ("ROUTE_JUNCTION", 5782, 5793, "RouteJunction.inward / canTransfer / ease"),
    ("ATTACK_HEADING", 5900, 5906, "attackHeading() (reads player.rail, player.trunkNormal, player.yaw)"),
    ("JUMP_VELOCITY", 5915, 5921, "jumpVelocity() (reads player.boostRemaining)"),
    ("SQUIRREL_GRAVITY", 6472, 6472, "SQUIRREL_GRAVITY = 30"),
    ("POUNCE_VELOCITY", 6473, 6481, "pounceVelocity() (reads pitch, player.focus, player.moveSpeed, player.boostRemaining)"),
    ("SPOTTED", 7027, 7051, "the spotted predicate statements inside updateHumans (reads player, pos, n, activeHouseInterior, time, crimeScenes)"),
    ("SEGMENT_BOX_ENTRY", 15786, 15807, "segmentBoxEntry(a, b, halfWidth, halfLength, minY, maxY)"),
    ("SWEPT_VEHICLE_HIT", 15808, 15851, "sweptVehicleHit(p0, p1, v0, v1, yaw0, yaw1, width, length, height)"),
]
assert block(7051, 7051).strip().endswith(';'), block(7051, 7051)
assert block(80, 80).startswith('function rng('), block(80, 80)
assert block(15808, 15808).startswith('function sweptVehicleHit('), block(15808, 15808)

out = []
out.append('"use strict";')
out.append('// GENERATED by tools/golden/gen_original.py from reference/v5_4_game.js (SHA-256 of that file is')
out.append('// recorded in data/harvest/manifest.json). Every block below is a byte-exact copy of the cited lines;')
out.append('// verifyVerbatim() re-reads the reference at run time and fails if any block drifted.')
out.append('// Only the surrounding glue (module-level state the original read from closure scope) is ours.')
out.append('const THREE = require("three");')
out.append('const crypto = require("node:crypto");')
out.append('const fs = require("node:fs");')
out.append('')
out.append('// ---- glue: module-level state the original functions read from the game scope ----')
out.append('const PI = Math.PI;')
out.append('const v = (x, y, z) => new THREE.Vector3(x, y, z); // L94')
out.append("let player = null; // the game's player object (L5127)")
out.append('let pitch = 0; // camera pitch (L5537)')
out.append('let activeHouseInterior = null; // L6248')
out.append('let time = 0; // L5543')
out.append('let crimeScenes = []; // L9165')
out.append('')
meta = []
for name, a, b, desc in BLOCKS:
    text = block(a, b)
    meta.append({"name": name, "from": a, "to": b, "sha256": hashlib.sha256(text.encode()).hexdigest(), "what": desc})
    out.append(f'// === verbatim reference/v5_4_game.js L{a}-{b}: {desc} ===')
    if name == "SPOTTED":
        out.append('function spottedPredicate(n, pos) {')
        out.append(text)
        out.append('  return { dist2, isVisible, inView, noise, gardenBlind, hedgeBlind, concealed, hotHere, remembered, radar, spotted };')
        out.append('}')
    else:
        out.append(text)
    out.append(f'// === end L{a}-{b} ===')
    out.append('')
out.append('const BLOCKS = ' + json.dumps(meta, indent=2) + ';')
out.append('''
function verifyVerbatim(referencePath) {
  if (!fs.existsSync(referencePath)) return { verified: false, reason: `reference not found: ${referencePath}` };
  const lines = fs.readFileSync(referencePath, "utf8").split("\\n");
  const bad = [];
  for (const b of BLOCKS) {
    const text = lines.slice(b.from - 1, b.to).join("\\n");
    const sha = crypto.createHash("sha256").update(text).digest("hex");
    if (sha !== b.sha256) bad.push(`${b.name} L${b.from}-${b.to}`);
  }
  if (bad.length) throw new Error(`verbatim blocks differ from the reference: ${bad.join(", ")}`);
  return { verified: true, blocks: BLOCKS.length };
}

// Setters for the closure state the original functions read.
function setPlayer(p) { player = p; }
function setPitch(x) { pitch = x; }
function setActiveHouseInterior(x) { activeHouseInterior = x; }
function setTime(t) { time = t; }
function setCrimeScenes(list) { crimeScenes = list; }

// finishTrafficFrame per-vehicle filter (L15878), not verbatim: the original is interleaved with game state.
function trafficTravelFilterSkips(travel, dt) {
  return travel < 1e-5 || travel > Math.max(12, dt * 80 + 2);
}

module.exports = {
  THREE, v, PI, rng, RouteMotion, RouteJunction, smoothstep, baseTerrainHeight, RIVER, riverCenter,
  inRiverDistrict, insideRiverWater, riverDeckAt, terrainHeight, hedgePatches, GARDEN_X, GARDEN_Z,
  attackHeading, jumpVelocity, SQUIRREL_GRAVITY, pounceVelocity, spottedPredicate, segmentBoxEntry,
  sweptVehicleHit, trafficTravelFilterSkips, BLOCKS, verifyVerbatim,
  setPlayer, setPitch, setActiveHouseInterior, setTime, setCrimeScenes,
};
''')
OUT.write_text('\n'.join(out))
print(f"wrote {OUT} with {len(BLOCKS)} verbatim blocks")
